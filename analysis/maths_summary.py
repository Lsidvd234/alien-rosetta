"""All maths runs side by side, read from their downloaded result files (results/kaggle/maths-*/).

    python analysis/maths_summary.py      -> rewrites the generated section at the end of results/maths.md

Groups: seed replicates of the three starts, partial starts (which glyphs need the meaning start), longer training
lengths, and dropped digit pairs (training without one single-digit multiplication). Numbers are exact-match
accuracy on 300 test items per row (char-level accuracy is in the run JSONs).
"""

from __future__ import annotations

import glob
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "results" / "maths.md"
MARK = "<!-- generated by analysis/maths_summary.py: everything below is rewritten -->"
GROUPS = {
    "Seed replicates (seed 0 / seed 1)": ["maths-meaning", "maths-meaning-s1", "maths-shuffled", "maths-shuffled-s1",
                                          "maths-mean", "maths-mean-s1"],
    "Partial starts (seed 0)": ["maths-meaning", "maths-digitsonly", "maths-opsonly", "maths-mean"],
    "Longer training lengths (add up to 4+4, mul up to 3x2 in training)": ["maths-meaning", "maths-meaning-longer",
                                                                        "maths-mean", "maths-mean-longer"],
    "Dropped digit pairs (meaning start; no training multiplication uses that single-digit product)":
        ["maths-meaning", "maths-meaning-drop56", "maths-meaning-drop34", "maths-meaning-drop22"],
    "Scratchpad (meaning start; long-multiplication working written before the answer)":
        ["maths-meaning", "maths-meaning-scratch", "maths-meaning-scratch-drop56"],
}


def load(run: str) -> dict | None:
    files = glob.glob(str(ROOT / "results" / "kaggle" / run / "results" / "*.json")) or \
        glob.glob(str(ROOT / "results" / "kaggle" / run / "*.json"))
    if not files:
        return None
    d = json.loads(Path(files[0]).read_text(encoding="utf-8"))
    tests = d.get("tests") or d.get("eval") or d
    return {k: (v.get("exact") if isinstance(v, dict) else v) for k, v in tests.items()
            if isinstance(v, (dict, int, float)) and not isinstance(v, bool)}


def table(runs: list[str]) -> str:
    data = {r: load(r) for r in runs}
    have = [r for r in runs if data[r]]
    missing = [r for r in runs if not data[r]]
    if not have:
        return "_not run yet_\n"
    keys = []
    for r in have:
        keys += [k for k in data[r] if k not in keys and isinstance(data[r][k], (int, float))]
    lines = ["| test | " + " | ".join(have) + " |", "|---|" + "---|" * len(have)]
    for k in keys:
        cells = [f"{data[r][k]:.3f}" if k in data[r] and data[r][k] is not None else "-" for r in have]
        lines.append(f"| {k} | " + " | ".join(cells) + " |")
    note = f"\n_not downloaded yet: {', '.join(missing)}_\n" if missing else "\n"
    return "\n".join(lines) + "\n" + note


def main() -> None:
    text = OUT.read_text(encoding="utf-8")
    head = text.split(MARK)[0].rstrip() + "\n\n"
    body = [MARK, "", "## All maths runs (2026-10-24)", ""]
    for title, runs in GROUPS.items():
        body += [f"### {title}", "", table(runs)]
    OUT.write_text(head + "\n".join(body), encoding="utf-8")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
